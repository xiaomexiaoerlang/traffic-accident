package com.casetracker.domain.model

import java.time.LocalDate

/**
 * 中国法定节假日与调休上班日数据。
 *
 * 数据来源：国务院办公厅历年《关于部分节假日安排的通知》
 *  - 2025 年安排：国办发明电〔2024〕6 号（2024-11-12 发布）
 *  - 2026 年安排：国办发明电〔2025〕7 号（2025-11-04 发布）
 *  - 2023 / 2024 年为已公布的历史安排
 *
 * 工作日规则：周末 + 法定节假日 = 休息日；调休上班日（周末补班）= 工作日。
 * 仅收录已由国务院正式公布的年份；未收录年份退化为仅跳过周末（见 CalendarUtil）。
 */
object ChinaHoliday {

    private fun d(y: Int, m: Int, day: Int): LocalDate = LocalDate.of(y, m, day)

    /** 生成 [start, endInclusive] 闭区间内的连续日期集合 */
    private fun range(start: LocalDate, endInclusive: LocalDate): Set<LocalDate> =
        generateSequence(start) { it.plusDays(1) }
            .takeWhile { !it.isAfter(endInclusive) }
            .toSet()

    /** 法定节假日（含调休连休形成的全部日期） */
    val HOLIDAYS: Set<LocalDate> =
        // 2023：元旦 12.31-1.2；春节 1.21-1.27；清明 4.5；劳动节 4.29-5.3；端午 6.22-6.24；中秋国庆 9.29-10.6
        range(d(2022, 12, 31), d(2023, 1, 2)) +
        range(d(2023, 1, 21), d(2023, 1, 27)) +
        range(d(2023, 4, 29), d(2023, 5, 3)) +
        range(d(2023, 6, 22), d(2023, 6, 24)) +
        range(d(2023, 9, 29), d(2023, 10, 6)) +
        // 2024：元旦 1.1；春节 2.10-2.17；清明 4.4-4.6；劳动节 5.1-5.5；端午 6.8-6.10；中秋 9.15-9.17；国庆 10.1-10.7
        range(d(2024, 1, 1), d(2024, 1, 1)) +
        range(d(2024, 2, 10), d(2024, 2, 17)) +
        range(d(2024, 4, 4), d(2024, 4, 6)) +
        range(d(2024, 5, 1), d(2024, 5, 5)) +
        range(d(2024, 6, 8), d(2024, 6, 10)) +
        range(d(2024, 9, 15), d(2024, 9, 17)) +
        range(d(2024, 10, 1), d(2024, 10, 7)) +
        // 2025：元旦 1.1；春节 1.28-2.4；清明 4.4-4.6；劳动节 5.1-5.5；端午 5.31-6.2；国庆中秋 10.1-10.8
        range(d(2025, 1, 1), d(2025, 1, 1)) +
        range(d(2025, 1, 28), d(2025, 2, 4)) +
        range(d(2025, 4, 4), d(2025, 4, 6)) +
        range(d(2025, 5, 1), d(2025, 5, 5)) +
        range(d(2025, 5, 31), d(2025, 6, 2)) +
        range(d(2025, 10, 1), d(2025, 10, 8)) +
        // 2026：元旦 1.1-1.3；春节 2.15-2.23；清明 4.4-4.6；劳动节 5.1-5.5；端午 6.19-6.21；中秋 9.25-9.27；国庆 10.1-10.7
        range(d(2026, 1, 1), d(2026, 1, 3)) +
        range(d(2026, 2, 15), d(2026, 2, 23)) +
        range(d(2026, 4, 4), d(2026, 4, 6)) +
        range(d(2026, 5, 1), d(2026, 5, 5)) +
        range(d(2026, 6, 19), d(2026, 6, 21)) +
        range(d(2026, 9, 25), d(2026, 9, 27)) +
        range(d(2026, 10, 1), d(2026, 10, 7))

    /** 调休上班日（周末补班） */
    val MAKEUP_WORKDAYS: Set<LocalDate> = setOf(
        // 2023：1.28、1.29、4.23、5.6、6.25、10.7、10.8
        d(2023, 1, 28), d(2023, 1, 29), d(2023, 4, 23), d(2023, 5, 6),
        d(2023, 6, 25), d(2023, 10, 7), d(2023, 10, 8),
        // 2024：2.4、2.18、4.7、4.28、5.11、9.14、9.29、10.12
        d(2024, 2, 4), d(2024, 2, 18), d(2024, 4, 7), d(2024, 4, 28),
        d(2024, 5, 11), d(2024, 9, 14), d(2024, 9, 29), d(2024, 10, 12),
        // 2025：1.26、2.8、4.27、5.10、9.28、10.11
        d(2025, 1, 26), d(2025, 2, 8), d(2025, 4, 27), d(2025, 5, 10),
        d(2025, 9, 28), d(2025, 10, 11),
        // 2026：1.4、2.14、2.28、5.9、9.20、10.10
        d(2026, 1, 4), d(2026, 2, 14), d(2026, 2, 28), d(2026, 5, 9),
        d(2026, 9, 20), d(2026, 10, 10)
    )

    /** 是否为法定节假日（含调休连休日） */
    fun isHoliday(date: LocalDate): Boolean = date in HOLIDAYS

    /** 是否为调休上班日（周末补班） */
    fun isMakeupWorkday(date: LocalDate): Boolean = date in MAKEUP_WORKDAYS
}
